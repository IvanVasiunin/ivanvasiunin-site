"""SQLAlchemy descriptions of the tables, for building queries (never for creating them).

Alembic owns the schema (ADR-0003): migration 0001 creates `chunks`. This module only lists the
columns that ingestion (ROADMAP 3.4) and retrieval (3.6) read and write, so both build their SQL
from one definition instead of strings. `metadata.create_all()` is never called on it.
"""

import sqlalchemy as sa
from pgvector.sqlalchemy import Vector
from sqlalchemy.dialects.postgresql import TSVECTOR

CHUNKS = sa.Table(
    "chunks",
    sa.MetaData(),
    sa.Column("id", sa.Text(), primary_key=True),
    sa.Column("content", sa.Text()),
    # No dimension here: the database column already is `vector(1536)`.
    sa.Column("embedding", Vector()),
    sa.Column("source_type", sa.Text()),
    sa.Column("category", sa.Text()),
    sa.Column("section", sa.Text()),
    sa.Column("project", sa.Text()),
    sa.Column("url", sa.Text()),
    sa.Column("source_date", sa.Date()),
    sa.Column("content_hash", sa.Text()),
    sa.Column("x", sa.REAL[float]()),
    sa.Column("y", sa.REAL[float]()),
    # Generated by Postgres from section + content; read-only for us (full-text search).
    sa.Column("tsv", TSVECTOR()),
    sa.Column("updated_at", sa.DateTime(timezone=True)),
)
